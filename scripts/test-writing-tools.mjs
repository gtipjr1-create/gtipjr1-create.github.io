import assert from "node:assert/strict";
import { mkdtemp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, relative } from "node:path";
import { generateWritingDraft } from "./migrate-writing.mjs";
import { validateWritingRepository } from "./writing-content.mjs";

const fixtureRoot = await mkdtemp(join(tmpdir(), "garry-writing-tools-"));

async function write(relativePath, contents) {
  const path = join(fixtureRoot, relativePath);
  await mkdir(join(path, ".."), { recursive: true });
  await writeFile(path, contents, "utf8");
}

function entry(frontmatter, body = "Fixture prose.\n") {
  return `---\n${frontmatter}---\n\n${body}`;
}

try {
  const source = "First paragraph — unchanged.\n\nSecond *paragraph* with [a link](https://example.com).\n";
  await write("input/source.md", source);
  await write(
    "input/metadata.json",
    JSON.stringify(
      {
        title: "A Review Draft",
        slug: "a-review-draft",
        type: "essay",
        summary: "A disposable migration-tool fixture.",
        category: "Practice",
        tags: ["practice"],
        sourceEvidence: "Disposable test fixture generated by the test suite.",
      },
      null,
      2,
    ),
  );

  const first = await generateWritingDraft({
    sourcePath: "input/source.md",
    metadataPath: "input/metadata.json",
    outputPath: "review/first.md",
    root: fixtureRoot,
  });
  const second = await generateWritingDraft({
    sourcePath: "input/source.md",
    metadataPath: "input/metadata.json",
    outputPath: "review/second.md",
    root: fixtureRoot,
  });
  assert.equal(first.generated, second.generated, "generation must be deterministic");
  assert.ok(first.generated.endsWith(source), "source Markdown must be preserved byte-for-byte");
  assert.match(first.generated, /status: "draft"/);
  assert.doesNotMatch(first.generated, /publishedDate/);
  assert.doesNotMatch(first.generated, /originalPublishedDate/);
  assert.doesNotMatch(first.generated, /sourceEvidence/);

  const missingSummary = JSON.parse(await readFile(join(fixtureRoot, "input/metadata.json"), "utf8"));
  delete missingSummary.summary;
  await write("input/missing-summary.json", JSON.stringify(missingSummary));
  await assert.rejects(
    generateWritingDraft({
      sourcePath: "input/source.md",
      metadataPath: "input/missing-summary.json",
      outputPath: "review/missing-summary.md",
      root: fixtureRoot,
    }),
    /summary must be a non-empty string/,
  );

  await assert.rejects(
    generateWritingDraft({
      sourcePath: "input/source.md",
      metadataPath: "input/metadata.json",
      outputPath: "src/content/writing/essays/a-review-draft/index.md",
      root: fixtureRoot,
    }),
    /cannot be written inside src\/content/,
  );

  const invalidMetadata = JSON.parse(await readFile(join(fixtureRoot, "input/metadata.json"), "utf8"));
  invalidMetadata.originalPublishedDate = "2020-05-12";
  await write("input/unproven-date.json", JSON.stringify(invalidMetadata));
  await assert.rejects(
    generateWritingDraft({
      sourcePath: "input/source.md",
      metadataPath: "input/unproven-date.json",
      outputPath: "review/unproven.md",
      root: fixtureRoot,
    }),
    /originalPublishedDateEvidence is required/,
  );

  await write(
    "src/content/writing/fragments/one/index.md",
    entry(
      'title: "One"\nslug: "one"\ntype: "fragment"\nsummary: "First."\ncategory: "Practice"\ntags: []\npublishedDate: "2026-08-07"\nfragmentNumber: 1\nstartHereOrder: 1\nstatus: "published"\nrelated: []\nconnections: []\n',
    ),
  );
  await write(
    "src/content/writing/essays/two/index.md",
    entry(
      'title: "Two"\nslug: "two"\ntype: "essay"\nsummary: "Second."\ncategory: "Practice"\ntags: []\nstatus: "draft"\nrelated: []\nconnections: []\n',
    ),
  );
  const validEntries = await validateWritingRepository({ root: fixtureRoot });
  assert.equal(validEntries.length, 2);

  await write(
    "src/content/writing/essays/two/index.md",
    entry(
      'title: "Two"\nslug: "two"\ntype: "essay"\nsummary: "Second."\ncategory: "Practice"\ntags: []\nstatus: "draft"\nstartHereOrder: 1\nrelated:\n  - "essay:two"\nconnections: []\nheroImage:\n  src: "/assets/writing/essays/two/missing.jpg"\n  alt: "Fixture"\n',
    ),
  );
  await write(
    "src/content/writing/fragments/duplicate/index.md",
    entry(
      'title: "Duplicate"\nslug: "one"\ntype: "fragment"\nsummary: "Duplicate."\ncategory: "Practice"\ntags: []\npublishedDate: "2026-08-07"\nfragmentNumber: 1\nstartHereOrder: 1\nstatus: "published"\nrelated: []\nconnections: []\n',
    ),
  );
  await write(
    "src/content/writing/essays/published/index.md",
    entry(
      'title: "Published"\nslug: "published"\ntype: "essay"\nsummary: "Published."\ncategory: "Practice"\ntags: []\npublishedDate: "2026-08-07"\nstatus: "published"\nrelated:\n  - "essay:two"\n  - "essay:missing"\nconnections: []\n',
    ),
  );
  await assert.rejects(
    validateWritingRepository({ root: fixtureRoot }),
    (error) =>
      /Duplicate writing key "fragment:one"/.test(error.message) &&
      /Duplicate fragmentNumber 1/.test(error.message) &&
      /Duplicate startHereOrder 1/.test(error.message) &&
      /cannot relate to itself/.test(error.message) &&
      /references missing related writing "essay:missing"/.test(error.message) &&
      /cannot expose draft related writing "essay:two"/.test(error.message) &&
      /referenced asset is missing/.test(error.message),
  );

  await rm(join(fixtureRoot, "src/content/writing/fragments/duplicate"), {
    recursive: true,
    force: true,
  });
  await rm(join(fixtureRoot, "src/content/writing/essays/published"), {
    recursive: true,
    force: true,
  });
  await write(
    "src/content/writing/essays/two/index.md",
    entry(
      'title: "Two"\nslug: "two"\ntype: "essay"\nsummary: "Second."\ncategory: "Practice"\ntags: []\nstatus: "draft"\nrelated: []\nconnections: []\n',
    ),
  );

  await write(
    "src/content/writing/essays/a-review-draft/index.md",
    entry(
      'title: "Existing"\nslug: "a-review-draft"\ntype: "essay"\nsummary: "Existing."\ncategory: "Practice"\nstatus: "draft"\n',
    ),
  );
  await assert.rejects(
    generateWritingDraft({
      sourcePath: "input/source.md",
      metadataPath: "input/metadata.json",
      outputPath: "review/third.md",
      root: fixtureRoot,
    }),
    /writing slug already exists/,
  );

  console.log(`Writing migration tests passed with disposable fixtures in ${relative(tmpdir(), fixtureRoot)}.`);
} finally {
  await rm(fixtureRoot, { recursive: true, force: true });
}
